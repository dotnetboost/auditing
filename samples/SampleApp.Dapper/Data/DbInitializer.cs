using Dapper;
using System.Data;

namespace SampleApp.Dapper.Data;

/// <summary>
/// Creates the sample's OWN two tables, which is what the EF Core sample's
/// <c>Database.EnsureCreatedAsync()</c> does for it. A real application uses migrations or a
/// deployment step.
/// <para>
/// <c>AuditEntries</c> and <c>AuditPropertyChanges</c> are <b>absent on purpose</b>: they are the
/// library's, and <c>UseDapper(..., migrateSchema: true)</c> in <c>Program.cs</c> creates them from
/// a hosted service when the host starts. That split is the whole point of the flag — your schema
/// stays yours, and the library's tables come out in the shape the EF Core store maps, so the same
/// database serves either.
/// </para>
/// <para>
/// The two halves never meet, so the order does not matter: this runs before <c>app.Run()</c> and
/// the library's hosted service runs just after it, and neither touches the other's tables.
/// </para>
/// </summary>
public static class DbInitializer
{
    /// <summary>Creates the sample's tables if they are absent. Idempotent.</summary>
    /// <param name="services">The application's services.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>A task that completes when the tables are present.</returns>
    public static async Task InitializeAsync(IServiceProvider services, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(services);

        await using var scope = services.CreateAsyncScope();

        // The scope's connection, resolved WITHOUT asking UnitOfWork for a transaction: DDL in
        // PostgreSQL is transactional and would work either way, but there is no request here to
        // commit one, and a rolled-back CREATE TABLE at the end of startup is a confusing way to
        // begin.
        var connection = scope.ServiceProvider.GetRequiredService<IDbConnection>();

        const string sql = """
            CREATE TABLE IF NOT EXISTS "Products" (
                "Id"           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "Name"         character varying(200) NOT NULL,
                "Price"        numeric(18,2)          NOT NULL,
                "Category"     character varying(100) NOT NULL,
                "SupplierCost" numeric(18,2)          NOT NULL,
                "ViewCount"    integer                NOT NULL DEFAULT 0
            );

            CREATE TABLE IF NOT EXISTS "StockChecks" (
                "Id"        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "ProductId" integer                  NOT NULL,
                "OnHand"    integer                  NOT NULL,
                "CheckedAt" timestamp with time zone NOT NULL
            );
            """;

        await connection.ExecuteAsync(new CommandDefinition(sql, cancellationToken: ct));
    }
}

using System.Globalization;
using System.Reflection;
using System.Text;

namespace DotNetBoost.Auditing.SurfaceTests;

/// <summary>
/// Renders an assembly's public surface as stable, readable text — the thing the baseline files
/// hold and a reviewer reads as a diff.
/// </summary>
/// <remarks>
/// <b>Fully qualified, and with nullability.</b> Both cost verbosity in a file nobody reads
/// top to bottom, and both buy a change that would otherwise pass: moving a public type to another
/// namespace breaks every <c>using</c> that named it, and turning a <c>string</c> into a
/// <c>string?</c> breaks the compilation of callers who never checked for null. Short names would
/// hide the first and no annotations would hide the second.
/// <para>
/// Nullability comes from <see cref="NullabilityInfoContext"/> rather than from reading
/// <c>NullableAttribute</c> by hand, which is where this kind of code usually goes wrong on nested
/// generics.
/// </para>
/// </remarks>
internal static class PublicSurface
{
    /// <summary>C# keywords for the types that would otherwise be spelled out.</summary>
    private static readonly Dictionary<Type, string> Aliases = new()
    {
        [typeof(void)]    = "void",
        [typeof(bool)]    = "bool",
        [typeof(byte)]    = "byte",
        [typeof(sbyte)]   = "sbyte",
        [typeof(char)]    = "char",
        [typeof(short)]   = "short",
        [typeof(ushort)]  = "ushort",
        [typeof(int)]     = "int",
        [typeof(uint)]    = "uint",
        [typeof(long)]    = "long",
        [typeof(ulong)]   = "ulong",
        [typeof(float)]   = "float",
        [typeof(double)]  = "double",
        [typeof(decimal)] = "decimal",
        [typeof(string)]  = "string",
        [typeof(object)]  = "object"
    };

    /// <summary>
    /// Members the compiler writes that no caller names: property and event accessors, and the two
    /// synthesised record members that are not callable from C#.
    /// </summary>
    private static readonly HashSet<string> Hidden = new(StringComparer.Ordinal)
    {
        "<Clone>$",
        "EqualityContract"
    };

    internal static string Render(Assembly assembly)
    {
        var nullability = new NullabilityInfoContext();
        var text        = new StringBuilder();

        text.AppendLine(CultureInfo.InvariantCulture, $"// Public surface of {assembly.GetName().Name}");
        text.AppendLine("//");
        text.AppendLine("// Generated by DotNetBoost.Auditing.SurfaceTests. A change here is a change to what");
        text.AppendLine("// consumers compile against: read the diff and decide whether it was meant, then commit it.");
        text.AppendLine("// To regenerate: DOTNETBOOST_SURFACE=update dotnet test tests/DotNetBoost.Auditing.SurfaceTests");

        var byNamespace = assembly.GetExportedTypes()
            .GroupBy(t => t.Namespace ?? string.Empty)
            .OrderBy(g => g.Key, StringComparer.Ordinal);

        foreach (var ns in byNamespace)
        {
            text.AppendLine();
            text.AppendLine(CultureInfo.InvariantCulture, $"namespace {ns.Key}");
            text.AppendLine("{");

            foreach (var type in ns.OrderBy(Name, StringComparer.Ordinal))
                AppendType(text, type, nullability);

            text.AppendLine("}");
        }

        return text.ToString();
    }

    private static void AppendType(StringBuilder text, Type type, NullabilityInfoContext nullability)
    {
        text.AppendLine(CultureInfo.InvariantCulture, $"    {Declaration(type)}");
        text.AppendLine("    {");

        foreach (var member in Members(type, nullability).OrderBy(m => m, StringComparer.Ordinal))
            text.AppendLine(CultureInfo.InvariantCulture, $"        {member}");

        text.AppendLine("    }");
    }

    /// <summary>The type's own line: modifiers, kind, name, and what it derives from.</summary>
    private static string Declaration(Type type)
    {
        var modifiers = new List<string> { type.IsNestedFamily ? "protected" : "public" };

        if (type.IsEnum)
        {
            modifiers.Add("enum");
        }
        else if (type.IsInterface)
        {
            modifiers.Add("interface");
        }
        else if (type.IsValueType)
        {
            if (type.IsByRefLike)
                modifiers.Add("ref");

            // Readonly is part of what a caller may do with the type, so it belongs here. There is
            // deliberately no attempt to say "record": record classes are detectable (the compiler
            // writes a <Clone>$ member) and record structs are not, and a baseline that said it for
            // some and not others would read as a difference where there is none. A record is a
            // class or a struct at the level this file describes, and its positional constructor,
            // Deconstruct and init accessors are all listed below anyway.
            if (type.GetCustomAttributes().Any(a => a.GetType().Name == "IsReadOnlyAttribute"))
                modifiers.Add("readonly");

            modifiers.Add("struct");
        }
        else
        {
            if (type is { IsAbstract: true, IsSealed: true })
                modifiers.Add("static");
            else if (type.IsAbstract)
                modifiers.Add("abstract");
            else if (type.IsSealed)
                modifiers.Add("sealed");

            modifiers.Add("class");
        }

        var declaration = string.Join(' ', modifiers) + " " + Name(type);

        // What it derives from and what it declares it implements. Dropping an interface is a
        // break for every caller that used the type through it, so it belongs in the baseline.
        var bases = new List<string>();

        if (type is { IsClass: true, BaseType: not null } && type.BaseType != typeof(object))
            bases.Add(Qualified(type.BaseType));

        bases.AddRange(type.GetInterfaces()
            .Where(i => i.IsPublic)
            // IEquatable<Self> is written by the compiler for every record; it says nothing a
            // reader of this file does not already know from the word "record".
            .Where(i => !(i.IsGenericType
                && i.GetGenericTypeDefinition() == typeof(IEquatable<>)
                && i.GetGenericArguments()[0] == type))
            .Select(i => Qualified(i))
            .OrderBy(n => n, StringComparer.Ordinal));

        if (type.IsEnum)
            bases.Add(Qualified(Enum.GetUnderlyingType(type)));

        return bases.Count == 0 ? declaration : $"{declaration} : {string.Join(", ", bases)}";
    }

    private static IEnumerable<string> Members(Type type, NullabilityInfoContext nullability)
    {
        const BindingFlags Flags =
            BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static |
            BindingFlags.DeclaredOnly;

        foreach (var member in type.GetMembers(Flags))
        {
            if (!IsVisible(member) || Hidden.Contains(member.Name))
                continue;

            switch (member)
            {
                case ConstructorInfo constructor:
                    yield return $"{Modifiers(constructor)}{Name(type)}({Parameters(constructor, nullability)});";
                    break;

                case MethodInfo method when !method.IsSpecialName || method.Name.StartsWith("op_", StringComparison.Ordinal):
                    yield return
                        $"{Modifiers(method)}{Returns(method, nullability)} {MethodName(method)}" +
                        $"({Parameters(method, nullability)});";
                    break;

                case PropertyInfo property:
                    yield return
                        $"{Modifiers(property)}{Nullable(property.PropertyType, nullability.Create(property))} " +
                        $"{property.Name} {{ {Accessors(property)}}}";
                    break;

                case FieldInfo field when !field.IsSpecialName:
                    yield return
                        $"{Modifiers(field)}{Nullable(field.FieldType, nullability.Create(field))} {field.Name}" +
                        (field.IsLiteral ? $" = {Literal(field)};" : ";");
                    break;

                case EventInfo e:
                    yield return $"event {Qualified(e.EventHandlerType!)} {e.Name};";
                    break;
            }
        }
    }

    /// <summary>Whether a caller outside the assembly can see this member.</summary>
    private static bool IsVisible(MemberInfo member) => member switch
    {
        // Enum members are fields; the enum's own visibility covers them.
        FieldInfo field             => field.IsPublic || field.IsFamily,
        MethodBase method           => method.IsPublic || method.IsFamily,
        PropertyInfo property       => IsVisible(property.GetMethod) || IsVisible(property.SetMethod),
        EventInfo e                 => e.AddMethod is not null && IsVisible(e.AddMethod),
        Type nested                 => nested.IsNestedPublic || nested.IsNestedFamily,
        _                           => false
    };

    private static bool IsVisible(MethodBase? method) => method is not null && IsVisible((MemberInfo)method);

    private static string Modifiers(MemberInfo member)
    {
        var parts = new List<string>();

        var isProtected = member switch
        {
            FieldInfo f     => f.IsFamily,
            MethodBase m    => m.IsFamily,
            PropertyInfo p  => (p.GetMethod ?? p.SetMethod)!.IsFamily,
            _               => false
        };

        parts.Add(isProtected ? "protected" : "public");

        var isStatic = member switch
        {
            FieldInfo f    => f.IsStatic,
            MethodBase m   => m.IsStatic,
            PropertyInfo p => (p.GetMethod ?? p.SetMethod)!.IsStatic,
            _              => false
        };

        if (member is FieldInfo { IsLiteral: true })
            parts.Add("const");
        else if (isStatic)
            parts.Add("static");

        if (member is FieldInfo { IsInitOnly: true, IsLiteral: false })
            parts.Add("readonly");

        if (member is MethodInfo { IsAbstract: true })
            parts.Add("abstract");
        else if (member is MethodInfo { IsVirtual: true, IsFinal: false } m2 && m2.GetBaseDefinition() != m2)
            parts.Add("override");
        else if (member is MethodInfo { IsVirtual: true, IsFinal: false })
            parts.Add("virtual");

        return string.Join(' ', parts) + " ";
    }

    private static string Accessors(PropertyInfo property)
    {
        var text = new StringBuilder();

        if (IsVisible(property.GetMethod))
            text.Append("get; ");

        if (IsVisible(property.SetMethod))
        {
            // init is a set accessor with a modreq; it reads differently to a caller, so it is
            // rendered differently here.
            var isInit = property.SetMethod!.ReturnParameter
                .GetRequiredCustomModifiers()
                .Any(m => m.Name == "IsExternalInit");

            text.Append(isInit ? "init; " : "set; ");
        }

        return text.ToString();
    }

    private static string MethodName(MethodInfo method) =>
        method.IsGenericMethodDefinition
            ? $"{method.Name}<{string.Join(", ", method.GetGenericArguments().Select(a => a.Name))}>"
            : method.Name;

    private static string Returns(MethodInfo method, NullabilityInfoContext nullability) =>
        method.ReturnType == typeof(void)
            ? "void"
            : Nullable(method.ReturnType, nullability.Create(method.ReturnParameter));

    private static string Parameters(MethodBase method, NullabilityInfoContext nullability) =>
        string.Join(", ", method.GetParameters().Select(p =>
        {
            var prefix = p.IsOut ? "out " : p.ParameterType.IsByRef ? "ref " : string.Empty;
            var type   = Nullable(p.ParameterType, nullability.Create(p));
            // `= default` and `= null` are different things to read, and reflection reports both as
            // a null DefaultValue — a CancellationToken rendered as `= null` would be a lie about a
            // signature, in a file whose only job is to state signatures exactly.
            var suffix = p.HasDefaultValue
                ? $" = {(p.DefaultValue is null && p.ParameterType.IsValueType && !IsNullableValueType(p.ParameterType)
                    ? "default"
                    : Literal(p.DefaultValue))}"
                : string.Empty;

            return $"{prefix}{type} {p.Name}{suffix}";
        }));

    /// <summary>The type as written, with <c>?</c> where the annotation says it may be null.</summary>
    private static string Nullable(Type type, NullabilityInfo info)
    {
        var rendered = Qualified(type.IsByRef ? type.GetElementType()! : type, info);

        // A nullable value type already reads as T? through Nullable<T>; only a reference type
        // needs the annotation added.
        return info.ReadState == NullabilityState.Nullable && !IsNullableValueType(type)
            ? rendered + "?"
            : rendered;
    }

    private static bool IsNullableValueType(Type type) =>
        type.IsGenericType && type.GetGenericTypeDefinition() == typeof(Nullable<>);

    private static string Qualified(Type type, NullabilityInfo? info = null)
    {
        if (type.IsByRef)
            return Qualified(type.GetElementType()!, info);

        if (type.IsArray)
        {
            var element = info?.ElementType;
            var inner   = element is null ? Qualified(type.GetElementType()!) : Nullable(type.GetElementType()!, element);

            return inner + "[]";
        }

        if (IsNullableValueType(type))
            return Qualified(type.GetGenericArguments()[0]) + "?";

        if (Aliases.TryGetValue(type, out var alias))
            return alias;

        if (type.IsGenericParameter)
            return type.Name;

        var name = type.FullName is { } full
            ? full.Split('`')[0].Replace('+', '.')
            : (type.Namespace is null ? type.Name : type.Namespace + "." + type.Name).Split('`')[0];

        if (!type.IsGenericType)
            return name;

        var arguments = type.GetGenericArguments();

        var rendered = arguments.Select((a, i) =>
            info is not null && i < info.GenericTypeArguments.Length
                ? Nullable(a, info.GenericTypeArguments[i])
                : Qualified(a));

        return $"{name}<{string.Join(", ", rendered)}>";
    }

    private static string Literal(FieldInfo field) => Literal(field.GetRawConstantValue());

    private static string Literal(object? value) => value switch
    {
        null      => "null",
        string s  => $"\"{s}\"",
        bool b    => b ? "true" : "false",
        char c    => $"'{c}'",
        Enum e    => e.ToString(),
        _         => Convert.ToString(value, CultureInfo.InvariantCulture) ?? "?"
    };

    /// <summary>The type's name as written, without its namespace.</summary>
    private static string Name(Type type)
    {
        var name = type.Name.Split('`')[0];

        return type.IsGenericTypeDefinition
            ? $"{name}<{string.Join(", ", type.GetGenericArguments().Select(a => a.Name))}>"
            : name;
    }
}

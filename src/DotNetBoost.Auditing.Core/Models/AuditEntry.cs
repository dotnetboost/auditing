namespace DotNetBoost.Auditing.Core.Models;

/// <summary>
/// One recorded change to one entity: who changed it, when, and which properties moved.
/// <para>
/// This is the stored row and also what a read returns. The other libraries in the suite separate
/// the two (<c>MediaFile</c> and <c>MediaFileInfo</c>) because a media row is mutable and a caller
/// holding one could write through it. An audit entry is append-only — nothing in this library ever
/// updates one — so a second read model would be two types carrying identical values.
/// </para>
/// </summary>
public sealed class AuditEntry
{
    /// <summary>
    /// The entry's identity, generated by the engine before the store sees it. A <c>Guid</c> rather
    /// than a store-assigned number, so an entry appended inside the caller's transaction has its
    /// id before the transaction commits — the EF Core interceptor needs one to hang property rows
    /// off while the save is still in flight.
    /// </summary>
    public Guid Id { get; set; }

    /// <summary>
    /// The entity's stored name — <c>"Product"</c> — by DotNetBoost Entity Addressing v1. With
    /// <see cref="EntityId"/> this is the whole of the addressing, and the pair is what an
    /// application joins on to reach the same entity's media or translations.
    /// </summary>
    public string EntityName { get; set; } = string.Empty;

    /// <summary>
    /// The entity's key as its stored string — <c>"42"</c>. One column serves <c>int</c>,
    /// <c>long</c>, <c>Guid</c> and <c>string</c> keys; see
    /// <see cref="Metadata.EntityKey.ToKeyString"/>.
    /// </summary>
    public string EntityId { get; set; } = string.Empty;

    /// <summary>What happened to the entity.</summary>
    public AuditAction Action { get; set; }

    /// <summary>
    /// Who made the change, from the registered <see cref="Interfaces.IAuditActorAccessor"/>.
    /// <c>null</c> means <b>not captured</b> — read it as "unknown", never as a claim about who
    /// acted. The default accessor returns <c>null</c>, so an application that has not wired one up
    /// gets honest nulls rather than a column full of <c>"system"</c>.
    /// </summary>
    public string? Actor { get; set; }

    /// <summary>
    /// One value per recording call, so the several entries of a single <c>SaveChanges</c> are
    /// identifiable as one edit. The ambient <see cref="System.Diagnostics.Activity"/> id when
    /// there is one — which makes a trail joinable to the traces of the request that caused it —
    /// otherwise a fresh value.
    /// </summary>
    public string CorrelationId { get; set; } = string.Empty;

    /// <summary>When the change happened, from the engine's <see cref="TimeProvider"/>. Always UTC.</summary>
    public DateTime OccurredAt { get; set; }

    /// <summary>
    /// Application-supplied context as JSON — a tenant, a reason, a ticket number — or <c>null</c>.
    /// Deliberately opaque and deliberately unqueried: the library neither parses it nor indexes
    /// it, which is what keeps it from becoming a second schema with no migrations.
    /// </summary>
    public string? Metadata { get; set; }

    /// <summary>
    /// One entry per property that changed. Empty is legal and meaningful — a
    /// <see cref="AuditAction.Deleted"/> entry recorded with
    /// <see cref="AuditingOptions.RecordDeletedValues"/> turned off says the entity was deleted and
    /// nothing more.
    /// </summary>
    public IList<AuditPropertyChange> Changes { get; } = [];
}
